// larghezza.dart — Quante celle occupa un carattere: zero, una o due.
//
// ── Perché è un file a sé ──────────────────────────────────────────────────
//
// Un terminale è una griglia, e la griglia non sa cos'è una lettera: sa
// quante CELLE si prende. Le lettere latine una, gli ideogrammi e le emoji
// due, gli accenti combinanti (U+0301 sopra una `e`) zero — stanno sulla
// cella di prima. Sbagliare qui non dà errore: dà `htop` con le colonne
// storte appena compare un nome di file giapponese.
//
// La tabella è quella di Unicode East Asian Width (W e F) più le emoji con
// presentazione grafica, ridotta a intervalli. Non è tutto Unicode: è quello
// che si incontra su una scrivania, e ogni intervallo si può provare.
library;

/// Larghezza in celle di `cp`: 0 (combinante o invisibile), 1, o 2.
int larghezzaCella(int cp) {
  if (cp < 0x20) return 0;
  if (cp < 0x7f) return 1;
  if (cp < 0xa0) return 0;
  // Combinanti e formattatori: si appoggiano alla cella prima.
  if (_dentro(cp, _zero)) return 0;
  if (_dentro(cp, _due)) return 2;
  return 1;
}

bool _dentro(int cp, List<int> intervalli) {
  // Ricerca binaria sugli intervalli [inizio, fine] appaiati.
  var basso = 0;
  var alto = intervalli.length ~/ 2 - 1;
  while (basso <= alto) {
    final mezzo = (basso + alto) >> 1;
    final a = intervalli[mezzo * 2];
    final b = intervalli[mezzo * 2 + 1];
    if (cp < a) {
      alto = mezzo - 1;
    } else if (cp > b) {
      basso = mezzo + 1;
    } else {
      return true;
    }
  }
  return false;
}

